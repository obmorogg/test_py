sales = {
    "Ноутбук": 7,
    "Мышь": 25,
    "Клавиатура": 14,
    "Монитор": 9,
    "Наушники": 18
}

prices = {
    "Ноутбук": 85000,
    "Мышь": 3500,
    "Клавиатура": 7200,
    "Монитор": 32000,
    "Наушники": 11500
}

report = {
  'All' : 0,
  'max count' : ['',0],
  'max value' : ['',0]
}



for i in sales.keys():
  report['All'] += sales[i] * prices[i]
  if report['max count'][-1] < sales[i]:
    report['max count'] = [i,sales[i]]
  if report['max value'][-1] < sales[i] * prices[i]:
    report['max value'] = [i,sales[i] * prices[i]]

print(report)