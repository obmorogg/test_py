"""

# Задание 6. Выручка по товарам

Даны два массива:

```python
prices = np.array([120, 80, 250, 150])

quantity = np.array([3, 5, 2, 4])
```

Первый содержит цены товаров.

Второй — количество проданных единиц.

Средствами NumPy получите выручку по каждому товару.

После этого определите:

* общую выручку;
* максимальную выручку;
* минимальную выручку.

Не используйте обычные Python-функции:

```python
sum()
min()
max()
```

и не перебирайте массив циклом.

### Пример результата

```text
Выручка:
[360 400 500 600]

Общая выручка: 1860
Максимум: 600
Минимум: 360
```

---
"""

import numpy as np

prices = np.array([120, 80, 250, 150])
quantity = np.array([3, 5, 2, 4])

revenue = prices * quantity

print(f"Выручка:\n{revenue}")

print(f"Общая выручка: {revenue.sum()}")
print(f"Максимум: {revenue.max()}")
print(f"Минимум: {revenue.min()}")