"""
# Задание 3. Шкала цен

Средствами NumPy сформируйте массив цен:

```text
50, 100, 150, 200, 250, 300
```

Затем сформируйте `6` равномерно распределённых коэффициентов от:

```text
0
```

до:

```text
0.25
```

Не перечисляйте значения массивов вручную и не используйте обычный `range()`.

Рассчитайте новые цены:

```text
цена * (1 + коэффициент)
```

Все вычисления выполните векторными операциями NumPy.

### Пример результата

```text
Цены:
[ 50 100 150 200 250 300]

Коэффициенты:
[0.   0.05 0.1  0.15 0.2  0.25]

Новые цены:
[ 50. 105. 165. 230. 300. 375.]
```
"""

import numpy as np

prices = np.array([50, 100, 150, 200, 250, 300])
coefficients = np.linspace(0, 0.25, 6)
new_prices = prices * (1 + coefficients)

print(f"Цены:\n{prices}")
print(f"Коэффициенты:\n{coefficients}")
print(f"Новые цены:\n{new_prices}")